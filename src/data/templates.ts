export function createNewCardFromTemplate(templateId: string): CardData {
  const template = DEFAULT_TEMPLATES.find((t) => t.id === templateId) || DEFAULT_TEMPLATES[0];
  const now = Date.now();
  
  return {
    id: `card_${now}_${Math.random().toString(36).substring(2, 8)}`,
    createdAt: now,
    updatedAt: now,
    isFavorite: false,
    templateCategory: template.category,
    heroName: template.cardData.heroName || 'Novo Herói 3D',
    subtitle: template.cardData.subtitle || 'Guerreiro Lendário',
    rarity: template.cardData.rarity || 'Raro',
    primaryColor: template.cardData.primaryColor || '#2563eb',
    secondaryColor: template.cardData.secondaryColor || '#dc2626',
    accentColor: template.cardData.accentColor || '#fde047',
    frameStyle: template.cardData.frameStyle || 'gold',
    illustrationUrl: template.cardData.illustrationUrl || PRESET_ARTWORKS[0].svgDataUri,
    illustrationTransform: template.cardData.illustrationTransform || {
      zoom: 1,
      rotation: 0,
      flipHorizontal: false,
      flipVertical: false,
      offsetX: 0,
      offsetY: 0,
    },
    power: template.cardData.power || {
      name: 'Super Golpe 3D',
      description: 'Um golpe mágico poderoso que derrota oponentes.',
      rule: 'Causa 40 de dano.',
      usageLimit: '1x por rodada',
      icon: 'star',
    },
    stats: template.cardData.stats || {
      hp: 100,
      maxHp: 100,
      attack: 80,
      defense: 60,
      speed: 70,
      energy: 3,
    },
    backConfig: template.cardData.backConfig || {
      autoGenerate: true,
      gameLogoText: 'CARD FORGE 3D',
      characterName: template.cardData.heroName || 'Novo Herói 3D',
      themeBackground: '#0f172a',
      heroShieldIcon: 'star',
      customQuote: 'Pronto para a batalha!',
      showQrCode: true,
    },
    enableFoil: template.cardData.enableFoil ?? true,
  };
}
